def backup_path(path: Path) -> Path:
    """Return the backup location used before overwriting a user file."""
    return Path(str(path) + BACKUP_SUFFIX)


def create_file(
    path: Path,
    content: str,
    executable: bool = False,
    dry_run: bool = False,
    backup_existing: bool = True,
) -> bool:
    """Write content to path, creating parent directories as needed.

    Existing files that were not generated by envytweaks are copied to
    ``<path>.envytweaks.bak`` first. If that backup already exists the write is
    refused, so a previous user backup can never be lost.

    Returns True on success (or dry-run), False when the write was refused or
    failed.
    """
    if backup_existing and path.exists() and not is_generated_file(path):
        backup = backup_path(path)
        if backup.exists():
            logging.error(
                "Refusing to overwrite '%s': backup '%s' already exists", path, backup
            )
            return False
        if dry_run:
            print(f"[DRY-RUN] Would back up {path} -> {backup}")
        else:
            try:
                shutil.copy2(path, backup)
                logging.info("Backed up %s to %s", path, backup)
            except OSError as e:
                logging.error("Failed to back up '%s': %s", path, e)
                return False

    if dry_run:
        exec_str = " (executable)" if executable else ""
        print(f"[DRY-RUN] Would create {path}{exec_str} ({len(content.encode('utf-8'))} bytes)")
        if logging.getLogger().isEnabledFor(logging.DEBUG):
            print(content)
        return True

    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        logging.info("Created file %s", path)
        if logging.getLogger().isEnabledFor(logging.DEBUG):
            print(content)
        if executable:
            path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
            logging.info("Added execution privilege to %s", path)
        return True
    except OSError as e:
        logging.error("Failed to create file '%s': %s", path, e)
        return False


def is_generated_file(path: Path) -> bool:
    """Return True only for files carrying an envytweaks/envycontrol marker."""
    try:
        content = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return False
    return any(marker in content for marker in GENERATED_MARKERS)


def restore_backup(path: Path, dry_run: bool = False) -> bool:
    """Restore a managed file from its backup.

    Returns True when a backup existed and was handled, False when there was
    nothing to restore.
    """
    backup = backup_path(path)
    if not backup.exists():
        return False

    if path.exists() and not is_generated_file(path):
        logging.warning(
            "Not restoring '%s': it was modified by the user (backup kept at '%s')",
            path,
            backup,
        )
        return True

    if dry_run:
        print(f"[DRY-RUN] Would restore {backup} -> {path}")
        return True

    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(backup, path)
        backup.unlink()
        logging.info("Restored %s from %s", path, backup)
    except OSError as e:
        logging.error("Failed to restore '%s' from '%s': %s", path, backup, e)
    return True


def restore_sddm_xsetup(dry_run: bool = False) -> bool:
    """Restore the original SDDM Xsetup from its backup, if one exists.

    Returns True when a backup was found (and restored), False otherwise so the
    caller can decide whether to fall back to removing a generated Xsetup.
    """
    if not SDDM_XSETUP_BACKUP_PATH.exists():
        return False

    if SDDM_XSETUP_PATH.exists() and not is_generated_file(SDDM_XSETUP_PATH):
        logging.warning(
            "Not restoring '%s': it was modified by the user (backup kept at '%s')",
            SDDM_XSETUP_PATH,
            SDDM_XSETUP_BACKUP_PATH,
        )
        return True

    if dry_run:
        print(
            f"[DRY-RUN] Would restore Xsetup backup "
            f"{SDDM_XSETUP_BACKUP_PATH} -> {SDDM_XSETUP_PATH}"
        )
        return True

    try:
        original = SDDM_XSETUP_BACKUP_PATH.read_text(encoding="utf-8")
    except OSError as e:
        logging.error("Failed to read Xsetup backup '%s': %s", SDDM_XSETUP_BACKUP_PATH, e)
        return True

    logging.info("Restoring Xsetup backup")
    if not create_file(SDDM_XSETUP_PATH, original, executable=True, backup_existing=False):
        logging.error("Keeping Xsetup backup because restore failed")
        return True

    try:
        SDDM_XSETUP_BACKUP_PATH.unlink()
        logging.info("Removed file %s", SDDM_XSETUP_BACKUP_PATH)
    except OSError as e:
        logging.error("Failed to remove Xsetup backup '%s': %s", SDDM_XSETUP_BACKUP_PATH, e)
    return True


def reset_sddm_xsetup(dry_run: bool = False) -> None:
    """Restore the SDDM Xsetup backup, or write the default empty script."""
    if restore_sddm_xsetup(dry_run=dry_run):
        return
    if SDDM_XSETUP_PATH.exists() and not is_generated_file(SDDM_XSETUP_PATH):
        logging.warning(
            "Not modifying '%s': it was not generated by envytweaks", SDDM_XSETUP_PATH
        )
        return
    create_file(
        SDDM_XSETUP_PATH,
        SDDM_XSETUP_CONTENT,
        executable=True,
        dry_run=dry_run,
        backup_existing=False,
    )


def _remove_generated(path: Path, dry_run: bool = False) -> None:
    """Remove a file only when it carries an envytweaks/envycontrol marker."""
    if not (path.exists() and is_generated_file(path)):
        return
    if dry_run:
        print(f"[DRY-RUN] Would remove file {path}")
        return
    try:
        path.unlink()
        logging.info("Removed file %s", path)
    except OSError as e:
        logging.error("Failed to remove file '%s': %s", path, e)


def cleanup(dry_run: bool = False, restore_backups: bool = False) -> None:
    """Remove only config files generated by envytweaks.

    Files without a generated marker are reported and left untouched. With
    ``restore_backups=True`` (used by ``--reset``) user backups are restored
    instead of being discarded.
    """
    for file_path in [*MANAGED_PATHS, *LEGACY_PATHS]:
        if file_path.exists() and not is_generated_file(file_path):
            logging.info("Skipping '%s': not generated by envytweaks", file_path)
        else:
            _remove_generated(file_path, dry_run=dry_run)

        if restore_backups:
            restore_backup(file_path, dry_run=dry_run)

    if restore_backups and restore_sddm_xsetup(dry_run=dry_run):
        return
    _remove_generated(SDDM_XSETUP_PATH, dry_run=dry_run)
